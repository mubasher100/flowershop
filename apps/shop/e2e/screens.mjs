// Screenshots of every screen at phone size, for design review.
// node e2e/screens.mjs <outdir>
import { webkit, devices } from "@playwright/test"
const OUT = process.argv[2]
const BACKEND = process.env.SHOP_TEST_BACKEND || "http://localhost:9000"
const res = await fetch(`${BACKEND}/auth/user/emailpass`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ email: process.env.SHOP_TEST_EMAIL || "dev@local.test", password: process.env.SHOP_TEST_PASSWORD || "local-dev-pass" }) })
const { token } = await res.json()
const browser = await webkit.launch()
const ctx = await browser.newContext({ ...devices["iPhone 13"], viewport: { width: 375, height: 740 } })
const login = await ctx.newPage()
await login.goto("http://localhost:5174/")
await login.waitForSelector("text=Sign in to run the shop")
await login.screenshot({ path: `${OUT}/01-login.png` })
await ctx.addInitScript((t) => localStorage.setItem("tt_shop_token", t), token)
const page = await ctx.newPage()
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png` })
await page.goto("http://localhost:5174/orders")
await page.waitForSelector("text=To do")
await page.waitForTimeout(600)
await shot("02-orders")
await page.locator("li button").first().click()
await page.waitForTimeout(400)
await shot("03-order-detail")
await page.keyboard.press("Escape")
await page.getByRole("link", { name: "Flowers" }).click()
await page.waitForSelector("[aria-label=Flowers] li")
await page.waitForTimeout(800)
await shot("04-flowers")
await page.getByRole("button", { name: "Select", exact: true }).click()
await page.locator("[aria-label=Flowers] li button").nth(0).click()
await page.locator("[aria-label=Flowers] li button").nth(1).click()
await page.locator("[aria-label=Flowers] li button").nth(2).click()
await shot("05-select")
await page.getByRole("toolbar").getByRole("button", { name: "Offer" }).click()
await page.waitForTimeout(400)
await shot("06-bulk-offer")
await page.keyboard.press("Escape")
await page.getByRole("toolbar").getByRole("button", { name: "Stock" }).click()
await page.waitForTimeout(400)
await shot("07-bulk-stock")
await page.keyboard.press("Escape")
await page.getByRole("button", { name: "Done" }).click()
await page.locator("[aria-label=Flowers] li button").first().click()
await page.waitForTimeout(500)
await shot("08-edit")
await page.keyboard.press("Escape")
await page.getByRole("button", { name: "+ Add flower" }).click()
await page.waitForTimeout(400)
await shot("09-add")
await page.keyboard.press("Escape")
await page.getByRole("link", { name: "Website" }).click()
await page.waitForTimeout(300)
await shot("10-website")
await browser.close()
console.log("ok")
