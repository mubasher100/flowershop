/**
 * Retrieves a cart by its ID. If no ID is provided, it will use the cart ID from the cookies.
 * @param cartId - optional - The ID of the cart to retrieve.
 * @returns The cart object if found, or null if not found.
 */
export async function retrieveCart(cartId?: string, fields?: string) {
  const id = cartId || (await getCartId())
  fields ??=
    "*items, *region, *items.product, *items.variant, *items.thumbnail, *items.metadata, +items.total, *promotions, +shipping_methods.name"

  if (!id) {
    return null
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  /**
   * Never cached.
   *
   * This used `force-cache` with a per-visitor tag, relying on `revalidateTag`
   * after every mutation to clear it. That stopped being enough once the
   * incremental cache started skipping the tag check on a regional hit — an
   * added item then took up to a minute to appear, so the bag looked empty
   * right after something was put in it.
   *
   * There was never much to win here anyway: a cart belongs to one visitor,
   * changes on every interaction, and comes back in about half a second.
   * Correctness is worth more than that.
   */
  return await sdk.client
    .fetch<HttpTypes.StoreCartResponse>(`/store/carts/${id}`, {
      method: "GET",
      query: {
        fields,
      },
      headers,
      cache: "no-store",
    })
    .then(({ cart }: { cart: HttpTypes.StoreCart }) => cart)
    .catch(() => null)
}

export async function getOrSetCart(countryCode: string) {
  const region = await getRegion(countryCode)

  if (!region) {
    throw new Error(`Region not found for country code: ${countryCode}`)
  }

  /**
   * Skip the lookup when we already hold a cart id.
   *
   * This fetched the cart on every add just to read back its region, which is
   * a round trip to the Store API — around half a second — before the add
   * itself could start. There is only one region, so the answer was always the
   * same. The id is enough to add a line item; if the cart has since expired,
   * createLineItem fails and the caller retries with a fresh one.
   */
  const existingId = await getCartId()

  const headers = {
    ...(await getAuthHeaders()),
  }

  let cart = existingId
    ? ({ id: existingId, region_id: region.id } as HttpTypes.StoreCart)
    : await retrieveCart(undefined, "id,region_id")

  if (!cart) {
    const locale = await getLocale()
    const cartResp = await sdk.store.cart.create(
      { region_id: region.id, locale: locale || undefined },
      {},
      headers
    )
    cart = cartResp.cart

    await setCartId(cart.id)

    const cartCacheTag = await getCacheTag("carts")
    revalidateTag(cartCacheTag)
  }

  if (cart && cart?.region_id !== region.id) {
    await sdk.store.cart.update(cart.id, { region_id: region.id }, {}, headers)
    const cartCacheTag = await getCacheTag("carts")
    revalidateTag(cartCacheTag)
  }

  return cart
}

export async function updateCart(data: HttpTypes.StoreUpdateCart) {
  const cartId = await getCartId()

  if (!cartId) {
    throw new Error("No existing cart found, please create one before updating")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  return sdk.store.cart
    .update(cartId, data, {}, headers)
    .then(async ({ cart }: { cart: HttpTypes.StoreCart }) => {
      const cartCacheTag = await getCacheTag("carts")
      revalidateTag(cartCacheTag)

      const fulfillmentCacheTag = await getCacheTag("fulfillment")
      revalidateTag(fulfillmentCacheTag)

      return cart
    })
    .catch(medusaError)
}

export async function addToCart({
  variantId,
  quantity,
  countryCode,
  metadata,
}: {
  variantId: string
  quantity: number
  countryCode: string
  /**
   * Per-item personalisation — the gift message and ribbon chosen on the
   * product page. It rides on the line item rather than the cart because two
   * bouquets in one order can go to different people with different notes.
   */
  metadata?: Record<string, string>
}) {
  if (!variantId) {
    throw new Error("Missing variant ID when adding to cart")
  }

  const cart = await getOrSetCart(countryCode)

  if (!cart) {
    throw new Error("Error retrieving or creating cart")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  await sdk.store.cart
    .createLineItem(
      cart.id,
      {
        variant_id: variantId,
        quantity,
        // Omitted entirely when empty, so a plain order carries no empty keys
        // for the shopkeeper to read past.
        ...(metadata && Object.keys(metadata).length ? { metadata } : {}),
      },
      {},
      headers
    )
    .then(async () => {
      const cartCacheTag = await getCacheTag("carts")
      revalidateTag(cartCacheTag)

      const fulfillmentCacheTag = await getCacheTag("fulfillment")
      revalidateTag(fulfillmentCacheTag)
    })
    .catch(medusaError)
}

